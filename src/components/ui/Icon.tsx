export interface IconProps extends Omit<ComponentProps<LucideIcon>, 'ref'> {
  name: IconName;
}

/** Themed lucide icon with a string-name API. */
export function Icon({ name, ...rest }: IconProps) {
  const Component = Icons[name];
  return <Component {...rest} />;
}
